"""Collect every saved result into docs/results.md, copy the key figures to
docs/figures/ and the small result files to docs/results/, so GitHub shows
the evidence behind every number in the README.

results/ is not committed (large, and regenerated by the scripts); docs/ is.
Numbers are read from the summary files, never typed by hand.

Run from PyCharm (right-click > Run) or:  python scripts/06_report.py
"""

from __future__ import annotations

import argparse
import json
import platform
import shutil
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ["numpy", "scipy", "scikit-image", "pandas", "matplotlib", "tifffile", "imageio", "cellpose", "torch"]

# Small result files that back the README's numbers: (source under results/, name under docs/results/)
EVIDENCE = [
    ("02_baseline_v2/params.json", "baseline_params.json"),
    ("02_baseline_v2/grid_training.csv", "baseline_grid_training.csv"),
    ("02_baseline_v2/validation_summary.json", "baseline_validation_summary.json"),
    ("03_cellpose/params.json", "cellpose_params.json"),
    ("03_cellpose/grid_training.csv", "cellpose_grid_training.csv"),
    ("03_cellpose/validation_summary.json", "cellpose_validation_summary.json"),
    ("04_test/summary.json", "test_summary.json"),
    ("04_test/per_image.csv", "test_per_image.csv"),
    ("05_measurements/summary.json", "measurements_summary.json"),
]


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--results", type=Path, default=PROJECT_ROOT / "results")
    p.add_argument("--docs", type=Path, default=PROJECT_ROOT / "docs")
    return p.parse_args()


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def f3(x) -> str:
    return f"{x:.3f}"


def pct(x, signed: bool = False) -> str:
    return f"{x:+.1%}" if signed else f"{x:.1%}"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def installed_versions() -> dict:
    """Versions of the libraries in the environment that generated this report."""
    out = {"python": platform.python_version(), "platform": platform.platform()}
    for name in PACKAGES:
        try:
            out[name] = version(name)
        except PackageNotFoundError:
            out[name] = "not installed"
    return out


def segmentation_rows(summaries: list[dict]) -> list[list[str]]:
    get = lambda key, fmt: [fmt(s[key]) for s in summaries]  # noqa: E731
    return [
        ["Average F1 (IoU 0.50–0.90)", *get("af1", f3)],
        ["F1 at IoU 0.5", *get("f1_50", f3)],
        ["Precision / recall at IoU 0.5", *[f"{s['precision_50']:.3f} / {s['recall_50']:.3f}" for s in summaries]],
        ["Area bias", *get("area_bias", lambda x: pct(x, signed=True))],
        ["Merges / splits", *[f"{s['merges']} / {s['splits']}" for s in summaries]],
        ["Missed / extra", *[f"{s['missed']} / {s['extra']}" for s in summaries]],
    ]


def main() -> None:
    args = parse_args()
    r, figures = args.results, args.docs / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    out = ["# Results", "",
           "Generated by `scripts/06_report.py` from the saved summaries; rerun it rather than editing by hand.", ""]

    test = load(r / "04_test" / "summary.json")
    if test:
        s = test["summary"]
        secs = test["median_seconds_per_image"]
        gpu = test["environment"].get("gpu", "CPU")
        rows = segmentation_rows([s["baseline"], s["cellpose"]])
        rows.append(["Median time per image", f"{secs['baseline']:.2f} s, one CPU core", f"{secs['cellpose']:.2f} s, {gpu}"])
        published = {**test["published_average_f1"], "**Baseline v2 (this project)**": s["baseline"]["af1"],
                     "**Cellpose-SAM (this project, has seen these images)**": s["cellpose"]["af1"]}
        out += ["## Test split (50 images, scored once)", "",
                table(["", "Baseline v2", "Cellpose-SAM¹"], rows), "",
                "¹ Cellpose has most likely been trained on these images (see README), so its score is a "
                "ceiling on seen data, not a generalisation result.", "",
                "### Compared with published results on the same test images", "",
                table(["Method", "Average F1"],
                      [[k, f3(v)] for k, v in sorted(published.items(), key=lambda kv: -kv[1])]),
                "", "Published numbers: Caicedo et al. 2019, *Cytometry A*.", "",
                "![F1 across IoU thresholds](figures/f1_by_iou.png)", "",
                "![Recall by nucleus size](figures/recall_by_size.png)", ""]

    meas = load(r / "05_measurements" / "summary.json")
    if meas and "dna_profile" not in meas:
        raise SystemExit("results/05_measurements was made by an older version of step 5; rerun "
                         "scripts/05_measurements.py first.")
    if meas:
        c, own, both, dp = meas["counts"], meas["agreement"], meas["agreement_found_by_both"], meas["dna_profile"]
        lo, hi = meas["thresholds"]["low"], meas["thresholds"]["high"]
        m = ["baseline", "cellpose"]
        within = lambda d, what: pct(d[what]["within ±10%"])  # noqa: E731
        rows = [
            ["Nucleus count error per image, mean / worst",
             *[f"{pct(c[k]['mean_abs_error'])} / {pct(c[k]['worst_abs_error'])}" for k in m]],
            ["Nuclei each method found (IoU > 0.5)", *[f"{own[k]['area']['nuclei']:,}" for k in m]],
            ["…area within ±10% of the annotated outline", *[within(own[k], "area") for k in m]],
            ["…DNA content within ±10%", *[within(own[k], "DNA content") for k in m]],
            ["Nuclei both methods found", *[f"{both[k]['area']['nuclei']:,}" for k in m]],
            ["…area within ±10% of the annotated outline", *[within(both[k], "area") for k in m]],
            ["…DNA content within ±10%", *[within(both[k], "DNA content") for k in m]],
            [f"High-DNA share of whole objects (annotated: {pct(dp['annotated']['high_share_of_whole'])})",
             *[pct(dp[k]["high_share_of_whole"]) for k in m]],
            ["…high-DNA objects that are merges (of 2 / of 3+ annotated nuclei)",
             *[f"{dp[k]['high_merges']} ({dp[k]['high_merges_of_two']} / {dp[k]['high_merges_of_three_or_more']})"
               for k in m]],
            ["…high-DNA share without the merges", *[pct(dp[k]["high_share_without_merges"]) for k in m]],
        ]
        out += ["## Downstream measurements (test split)", "",
                "DNA content = background-subtracted Hoechst intensity summed over an object, relative to the "
                f"image's median annotated nucleus (= 1). Whole objects: at least {lo}; high-DNA objects: more "
                f"than {hi}. In an untreated culture the high-DNA objects would mostly be G2/M cells, but every "
                "BBBC039 image shows a different compound, so the scale is used to compare outlines, not to "
                "assign cell-cycle phases.", "",
                table(["", "Baseline v2", "Cellpose-SAM"], rows), "",
                "![DNA content](figures/dna_content.png)", "",
                "![Counts per image](figures/counts.png)", ""]

    base_val = load(r / "02_baseline_v2" / "validation_summary.json")
    cp_val = load(r / "03_cellpose" / "validation_summary.json")
    if base_val and cp_val:
        out += ["## Validation split (used during development)", "",
                table(["", "Baseline v1", "Baseline v2", "Cellpose-SAM"],
                      segmentation_rows([base_val["version_1"], base_val["version_2"], cp_val["cellpose_chosen"]])),
                "", "![Seed strategies](figures/seed_strategies.png)", ""]

    copies = {
        r / "04_test" / "f1_by_iou.png": "f1_by_iou.png",
        r / "04_test" / "recall_by_size.png": "recall_by_size.png",
        r / "05_measurements" / "dna_content.png": "dna_content.png",
        r / "05_measurements" / "counts.png": "counts.png",
        r / "02_baseline_v2" / "seed_strategies.png": "seed_strategies.png",
    }
    copies.update({p: f"overlays/{p.name}" for p in sorted((r / "04_test" / "overlays").glob("*.png"))})
    copied = []
    for src, name in copies.items():
        if src.exists():
            (figures / name).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, figures / name)
            copied.append(name)
    if any(n.startswith("overlays/") for n in copied):
        out += ["## Error overlays (test split)", ""]
        out += [f"![{Path(n).stem}](figures/{n})" for n in copied if n.startswith("overlays/")]
        out.append("")

    evidence = args.docs / "results"
    evidence.mkdir(parents=True, exist_ok=True)
    saved = []
    for src, name in EVIDENCE:
        if (r / src).exists():
            shutil.copy2(r / src, evidence / name)
            saved.append(name)
    env = {"report_environment": installed_versions()}
    if test:
        env["test_run_environment"] = test.get("environment", {})
    (evidence / "environment.json").write_text(json.dumps(env, indent=2))
    saved.append("environment.json")
    out += ["## Result files", "",
            "The small files behind these tables are in [results/](results/): frozen settings, the "
            "training grid searches, validation and test summaries, per-image test scores and library "
            "versions. Predicted masks and per-object tables are regenerated by the scripts.", ""]

    report = "\n".join(out)
    (args.docs / "results.md").write_text(report, encoding="utf-8")
    print(report)
    print(f"\nWrote {args.docs / 'results.md'}, copied {len(copied)} figures to {figures} "
          f"and {len(saved)} result files to {evidence}")


if __name__ == "__main__":
    main()
